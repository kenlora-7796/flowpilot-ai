const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const PORT = Number(process.env.PORT || 3010);
const ROOT = path.join(__dirname, 'public');
const MIME = {'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8'};
function send(res, code, obj) {res.writeHead(code, {'Content-Type':'application/json; charset=utf-8','Cache-Control':'no-store'});res.end(JSON.stringify(obj));}
function sample(request) {
 const subject = request.trim().replace(/[.!?]+$/, '');
 return [
  {id:'task-1', descriptionEnglish:`Clarify the goal and success criteria for: ${subject}`,priority:'High',completed:false},
  {id:'task-2', descriptionEnglish:`List the resources and people needed for: ${subject}`,priority:'High',completed:false},
  {id:'task-3', descriptionEnglish:`Break ${subject} into actionable steps and assign owners`,priority:'Medium',completed:false},
  {id:'task-4', descriptionEnglish:`Set a realistic timeline and review progress`,priority:'Medium',completed:false},
  {id:'task-5', descriptionEnglish:`Document results and identify improvements`,priority:'Low',completed:false}
 ];
}
function parseTasks(text) {
 const cleaned = text.replace(/^```(?:json)?\s*/i,'').replace(/\s*```$/,'');
 const parsed = JSON.parse(cleaned);
 const list = Array.isArray(parsed) ? parsed : parsed.tasks;
 if (!Array.isArray(list) || list.length < 1 || list.length > 12) throw new Error('Invalid AI task list');
 return list.map((t,i) => {
  if (typeof t.description !== 'string' || !t.description.trim() || !['High','Medium','Low'].includes(t.priority)) throw new Error('Invalid AI task');
  return {id:`task-${i+1}`,descriptionEnglish:t.description.trim().slice(0,300),priority:t.priority,completed:false};
 });
}
async function readBody(req) {
 let body='';
 for await (const chunk of req) {body+=chunk;if(body.length>12000) throw new Error('Request too large');}
 return JSON.parse(body || '{}');
}
async function generate(request) {
 const key = process.env.GEMINI_API_KEY;
 if (!key) return {mode:'demo',notice:'DEMO MODE — sample workflow, not generated by AI.',tasks:sample(request)};
 const model = process.env.GEMINI_MODEL || 'gemini-2.5-flash';
 const controller = new AbortController();
 const timeout = setTimeout(()=>controller.abort(),15000);
 try {
  const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`,{
   method:'POST',signal:controller.signal,
   headers:{'Content-Type':'application/json','x-goog-api-key':key},
   body:JSON.stringify({contents:[{parts:[{text:`Create 4 to 7 concrete tasks for this small-business request: ${request}. Return only a JSON object with a tasks array. Each task has description (short English sentence) and priority (exactly High, Medium, or Low). Do not include markdown.`}]}],generationConfig:{responseMimeType:'application/json'}})
  });
  if(!response.ok) throw new Error(`AI service returned HTTP ${response.status}`);
  const data=await response.json();
  const text=data.candidates?.[0]?.content?.parts?.map(p=>p.text||'').join('');
  if(!text) throw new Error('AI returned no text');
  return {mode:'ai',notice:'Generated with Gemini AI',tasks:parseTasks(text)};
 } finally {clearTimeout(timeout);}
}

function demoTranslations(tasks) {
 const templates = [
  'Aclarar el objetivo y los criterios de exito para: ',
  'Enumerar los recursos y las personas necesarias para: ',
  'Dividir la solicitud en pasos concretos y asignar responsables: ',
  'Establecer un calendario realista y revisar el progreso',
  'Documentar los resultados e identificar mejoras'
 ];
 return tasks.map((task, index) => {
  const original = String(task.descriptionEnglish || '');
  const subject = original.includes(': ') ? original.split(': ').slice(1).join(': ') : original;
  return index < 3 ? templates[index] + subject : (templates[index] || original);
 });
}
async function translateTasks(tasks, mode) {
 if(mode === 'demo') return {mode:'demo',translations:demoTranslations(tasks),notice:'DEMO MODE - sample Spanish templates; request text may remain in English.'};
 const key = process.env.GEMINI_API_KEY;
 if(!key) throw new Error('Gemini key unavailable; cannot translate live AI tasks');
 const model = process.env.GEMINI_MODEL || 'gemini-2.5-flash';
 const controller = new AbortController();
 const timeout = setTimeout(() => controller.abort(), 15000);
 try {
  const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent`, {
   method:'POST', signal:controller.signal,
   headers:{'Content-Type':'application/json','x-goog-api-key':key},
   body:JSON.stringify({
    contents:[{parts:[{text:'Translate each English task into natural Spanish, preserving meaning and order. Return only JSON: {"translations":["...", "..."]}. Do not add tasks. Tasks: '+JSON.stringify(tasks.map(t=>t.descriptionEnglish))}]}],
    generationConfig:{responseMimeType:'application/json'}
   })
  });
  if(!response.ok) throw new Error('Translation service returned HTTP '+response.status);
  const data=await response.json();
  const raw=data.candidates?.[0]?.content?.parts?.map(p=>p.text||'').join('');
  const parsed=JSON.parse(raw.replace(/^```(?:json)?\s*/i,'').replace(/\s*```$/,''));
  if(!Array.isArray(parsed.translations) || parsed.translations.length !== tasks.length || parsed.translations.some(t=>typeof t!=='string' || !t.trim() || t.length>500)) throw new Error('Invalid translation response');
  return {mode:'ai',translations:parsed.translations.map(t=>t.trim()),notice:'Translated with Gemini AI'};
 } finally {clearTimeout(timeout);}
}
const server=http.createServer(async(req,res)=>{
 const url=new URL(req.url,'http://localhost');
 if(req.method==='POST' && url.pathname==='/api/translate') {
  try {
   const body=await readBody(req);
   if(!Array.isArray(body.tasks) || body.tasks.length<1 || body.tasks.length>12 || !['ai','demo'].includes(body.mode) || body.tasks.some(t=>typeof t?.descriptionEnglish!=='string' || !t.descriptionEnglish.trim() || t.descriptionEnglish.length>300)) return send(res,400,{error:'Invalid translation request'});
   return send(res,200,await translateTasks(body.tasks,body.mode));
  } catch(e) {return send(res,503,{error:'Translation failed: '+e.message});}
 }
 if(req.method==='POST' && url.pathname==='/api/workflow') {
  try {
   const body=await readBody(req);
   if(typeof body.request!=='string' || !body.request.trim() || body.request.length>1500) return send(res,400,{error:'Enter a business request (1–1500 characters).'});
   const result=await generate(body.request.trim());
   return send(res,200,result);
  } catch(e) {return send(res,503,{error:`Workflow generation failed: ${e.message}. Check your AI configuration or remove GEMINI_API_KEY to try labeled demo mode.`});}
 }
 if(req.method!=='GET' && req.method!=='HEAD') return send(res,405,{error:'Method not allowed'});
 const files={'/':'index.html','/index.html':'index.html','/style.css':'style.css','/app.js':'app.js'};
 const filename=files[url.pathname];
 if(!filename) return send(res,404,{error:'Not found'});
 const filepath=path.join(ROOT,filename);
 fs.readFile(filepath,(err,content)=>{
  if(err) return send(res,404,{error:'Not found'});
  res.writeHead(200,{'Content-Type':MIME[path.extname(filepath)],'X-Content-Type-Options':'nosniff'});
  res.end(req.method==='HEAD'?'':content);
 });
});
if(require.main===module) server.listen(PORT,()=>console.log(`FlowPilot AI running at http://localhost:${PORT}`));
module.exports={server,sample,parseTasks};
